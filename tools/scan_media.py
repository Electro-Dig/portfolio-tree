"""Scan a media folder and write <content folder>/media.js — the size, duration and sound of every file — which the tree needs
for its layout. Videos also get a poster frame (<name>.poster.jpg) if they do not have one yet. Run it after adding media.
Needs ffprobe / ffmpeg on PATH.

    python tools/scan_media.py                      # content/media → content/media.js
    python tools/scan_media.py my-content/media     # another content folder
"""
import json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MEDIA = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(ROOT, "content", "media")
OUT = os.path.join(os.path.dirname(MEDIA), "media.js")
IMG = (".jpg", ".jpeg", ".png", ".webp", ".gif")
VID = (".mp4", ".webm", ".mov", ".m4v")


def probe(path):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "stream=codec_type,width,height:format=duration", "-of", "json", path],
                       capture_output=True, text=True)
    j = json.loads(r.stdout or "{}")
    st = j.get("streams", [])
    v = next((s for s in st if s.get("codec_type") == "video"), {})
    return v.get("width"), v.get("height"), float(j.get("format", {}).get("duration") or 0), any(s.get("codec_type") == "audio" for s in st)


out = {}
for name in sorted(os.listdir(MEDIA)):
    path = os.path.join(MEDIA, name)
    low = name.lower()
    if not os.path.isfile(path) or low.endswith(".poster.jpg"):
        continue
    if low.endswith(IMG):
        w, h, _, _ = probe(path)
        out[name] = {"w": w, "h": h}
    elif low.endswith(VID):
        w, h, dur, audio = probe(path)
        poster = os.path.splitext(name)[0] + ".poster.jpg"
        if not os.path.exists(os.path.join(MEDIA, poster)):
            subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", str(min(1.0, dur / 3)), "-i", path, "-frames:v", "1", "-q:v", "4",
                            os.path.join(MEDIA, poster)], check=False)
        out[name] = {"w": w, "h": h, "dur": round(dur, 2), "audio": audio, "poster": poster}
with open(OUT, "w", encoding="utf-8") as f:
    body = ",\n".join(f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v)}" for k, v in out.items())
    f.write("// generated by tools/scan_media.py — do not edit by hand\nwindow.MEDIA = {\n" + body + "\n};\n")
print(f"{len(out)} files -> {OUT}")
